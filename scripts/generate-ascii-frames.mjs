// Pre-generates rail 3's ASCII block (docs/redesign-spec.md phase 3: "Pre-
// generate the frames at build time and cycle them; do not convert an image
// to ASCII in the browser every tick"). Run manually with `node
// scripts/generate-ascii-frames.mjs` whenever the pattern needs regenerating
// — it is not part of `next build`, the same way lib/data.ts's GH_COUNTS is
// a checked-in static snapshot rather than a live/build-time fetch.
//
// A seeded value-noise field, sampled at a drifting offset per frame (a
// cheap plasma/dither effect — "flow field, dithered noise, something
// ambient" per the spec), mapped to a density ramp of characters. Single
// colour by design: only glyph coverage carries the "intensity", so the
// block re-colours for free with `--accent` in CSS, matching every theme
// with zero per-theme frame data.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const COLS = 30;
const ROWS = 15;
const FRAME_COUNT = 60;
const SEED = 1337;
// Light -> dark. Kept short and hand-picked for even visual steps rather
// than a long photographic ramp — this is an abstract texture, not a tone-
// mapped image.
const RAMP = " .:-=+*#%@";

function hash(x, y, seed) {
  const h = Math.sin(x * 127.1 + y * 311.7 + seed * 74.7) * 43758.5453123;
  return h - Math.floor(h);
}

function smoothNoise(x, y, seed) {
  const xi = Math.floor(x);
  const yi = Math.floor(y);
  const xf = x - xi;
  const yf = y - yi;
  const u = xf * xf * (3 - 2 * xf);
  const v = yf * yf * (3 - 2 * yf);
  const a = hash(xi, yi, seed);
  const b = hash(xi + 1, yi, seed);
  const c = hash(xi, yi + 1, seed);
  const d = hash(xi + 1, yi + 1, seed);
  return a + (b - a) * u + (c - a) * v + (a - b - c + d) * u * v;
}

// Two octaves for a bit of texture instead of flat blobs.
function fbm(x, y, seed) {
  return smoothNoise(x, y, seed) * 0.65 + smoothNoise(x * 2.3, y * 2.3, seed + 91) * 0.35;
}

function buildFrame(t) {
  // Drift diagonally through the noise field over the loop — a cheap "flow"
  // read without simulating actual particles/vectors.
  const driftX = Math.cos(t * 0.11) * 2.2 + t * 0.05;
  const driftY = Math.sin(t * 0.09) * 1.6 + t * 0.035;
  const lines = [];
  for (let row = 0; row < ROWS; row++) {
    let line = "";
    for (let col = 0; col < COLS; col++) {
      const n = fbm(col * 0.32 + driftX, row * 0.32 + driftY, SEED);
      const level = Math.min(RAMP.length - 1, Math.max(0, Math.floor(n * RAMP.length)));
      line += RAMP[level];
    }
    lines.push(line);
  }
  return lines.join("\n");
}

const frames = [];
for (let f = 0; f < FRAME_COUNT; f++) {
  frames.push(buildFrame(f));
}

const out = `// GENERATED by scripts/generate-ascii-frames.mjs — do not hand-edit.
// Rail 3's ambient ASCII block (docs/redesign-spec.md phase 3). Re-run the
// script to regenerate; see it for how these frames are built.

export const ASCII_FRAME_COLS = ${COLS};
export const ASCII_FRAMES: string[] = ${JSON.stringify(frames, null, 2)};
`;

const __dirname = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(__dirname, "..", "lib", "asciiFrames.ts"), out);
console.log(`Wrote ${frames.length} frames (${COLS}x${ROWS}) to lib/asciiFrames.ts`);
